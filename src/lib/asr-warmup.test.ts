import { expect, test, vi } from "vitest";
import { warmUpAsrModel } from "./asr-warmup";

test("warms a model with inputs generated by its own processor", async () => {
  const modelInputs = { input_features: { dims: [1, 128, 3000] } };
  const processor = vi.fn().mockResolvedValue(modelInputs);
  const generate = vi.fn().mockResolvedValue(undefined);

  await warmUpAsrModel({ processor, model: { generate } });

  expect(processor).toHaveBeenCalledExactlyOnceWith(expect.any(Float32Array));
  expect(generate).toHaveBeenCalledExactlyOnceWith({ ...modelInputs, max_new_tokens: 1 });
  expect(processor.mock.calls[0][0]).toHaveLength(1600);
});
